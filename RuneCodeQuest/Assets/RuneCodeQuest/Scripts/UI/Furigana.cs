        /// <summary>文章を「ふつうの文字」と「ふりがな付きの漢字」に分けた1かたまり</summary>
        public struct Piece
        {
            public string Text;
            public string Ruby; // null ならふりがななし

            public Piece(string text, string ruby)
            {
                Text = text;
                Ruby = ruby;
            }
        }

        private class Entry
        {
            public string Key;     // 照合する文字列（例: "行こう"）
            public Piece[] Pieces; // 分けた結果
        }

        private static Dictionary<char, List<Entry>> index;
        private static readonly HashSet<char> warned = new HashSet<char>();

        public static bool IsKanji(char c) => (c >= '一' && c <= '鿿') || c == '々';

        public static bool HasKanji(string s)
        {
            if (string.IsNullOrEmpty(s)) return false;
            foreach (char c in s) if (IsKanji(c)) return true;
            return false;
        }

        /// <summary>ふりがなを付けて分ける（色タグなどは含まない、ふつうの文章を渡す）</summary>
        public static List<Piece> Split(string text)
        {
            if (index == null) BuildIndex();
            var result = new List<Piece>();
            var plain = new System.Text.StringBuilder();
            int i = 0;
            while (i < text.Length)
            {
                Entry best = null;
                if (index.TryGetValue(text[i], out var candidates))
                {
                    foreach (var e in candidates)
                    {
                        if (string.CompareOrdinal(text, i, e.Key, 0, e.Key.Length) == 0 && (best == null || e.Key.Length > best.Key.Length))
                            best = e;
                    }
                }

                if (best == null)
                {
                    if (IsKanji(text[i]) && warned.Add(text[i]))
                        Debug.LogWarning($"[ふりがな] 辞書にない漢字: 「{text[i]}」（Furigana.cs の Entries に追加してください）");
                    plain.Append(text[i]);
                    i++;
                    continue;
                }

                foreach (var p in best.Pieces)
                {
                    if (p.Ruby == null)
                    {
                        plain.Append(p.Text);
                    }
                    else
                    {
                        if (plain.Length > 0) { result.Add(new Piece(plain.ToString(), null)); plain.Clear(); }
                        result.Add(p);
                    }
                }
                i += best.Key.Length;
            }
            if (plain.Length > 0) result.Add(new Piece(plain.ToString(), null));
            return result;
        }

        private static void BuildIndex()
        {
            index = new Dictionary<char, List<Entry>>();
            foreach (string markup in Entries)
            {
                var pieces = new List<Piece>();
                var key = new System.Text.StringBuilder();
                int i = 0;
                while (i < markup.Length)
                {
                    if (markup[i] == '{')
                    {
                        int bar = markup.IndexOf('|', i);
                        int close = markup.IndexOf('}', i);
                        string kanji = markup.Substring(i + 1, bar - i - 1);
                        string ruby = markup.Substring(bar + 1, close - bar - 1);
                        pieces.Add(new Piece(kanji, ruby));
                        key.Append(kanji);
                        i = close + 1;
                    }
                    else
                    {
                        pieces.Add(new Piece(markup[i].ToString(), null));
                        key.Append(markup[i]);
                        i++;
                    }
                }
                var entry = new Entry { Key = key.ToString(), Pieces = pieces.ToArray() };
                char first = entry.Key[0];
                if (!index.TryGetValue(first, out var list)) index[first] = list = new List<Entry>();
                list.Add(entry);
            }
        }
