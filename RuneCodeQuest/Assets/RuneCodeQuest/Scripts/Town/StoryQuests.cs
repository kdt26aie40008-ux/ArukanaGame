    /// <summary>ストーリークエストの種類</summary>
    public enum StoryKind
    {
        Talk,        // 決められた町の人に 話を聞く
        Investigate, // 地図の印の場所を 調べる（アルカナが出ることもある）
    }

    /// <summary>
    /// ストーリークエスト（プログラミングではない、お話を進めるクエスト）。
    /// 建物1つごとに1つあり、終えると 依頼板で その建物の依頼（町づくり）が受けられるようになる。
    /// 村の さいごのストーリークエスト（旅立ち）を終えると、次の国へ行ける。
    /// </summary>
    public class StoryQuest
    {
        public int Village;            // どの村のクエストか
        public int Index;              // 村の中の順番（0〜）
        public string Title;
        public StoryKind Kind;
        public int After;              // この番号の建物が直ったら始まる（0 なら村に着いたら すぐ）。終えると After+1 番の建物の依頼が受けられる
        public string[] Start;         // 始まるときに 師匠が話すこと
        public string[] Targets;       // 話を聞く人（Talk）
        public string[][] TalkLines;   // それぞれの人が話すこと（Targets と同じ順）
        public int X, Y;               // 調べる場所（Investigate）
        public string SpotName;
        public string[] Look;          // 調べたときの話（Investigate）
        public bool Battle;            // 調べると アルカナが出る（たおすとクリア）
        public string[] Done;          // 終わったときの話
        public int Coins;              // ほうびの金貨

        /// <summary>記録の番号（村ごとに10ずつ）</summary>
        public int Id => Village * 10 + Index;

        /// <summary>やること（左上の目的・師匠の話に出す）</summary>
        public string Goal => Kind == StoryKind.Talk ? $"{string.Join("・", Targets)}に 話を聞く" : $"「{SpotName}」を調べる（キラキラの印）";
    }

