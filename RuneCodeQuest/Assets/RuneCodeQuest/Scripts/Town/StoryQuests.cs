        /// <summary>その村の ストーリークエスト（順番どおり）</summary>
        public static IEnumerable<StoryQuest> Of(int village)
        {
            foreach (var q in All) if (q.Village == village) yield return q;
        }

        /// <summary>その建物の依頼を 受けられるようにする ストーリークエスト（なければ null）</summary>
        public static StoryQuest GateOf(BuildingInfo b)
        {
            foreach (var q in All) if (q.Village == b.Village && q.After == b.Number - 1) return q;
            return null;
        }
