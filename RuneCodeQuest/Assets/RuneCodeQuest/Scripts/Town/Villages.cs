        private static SpotInfo[] Spots(params string[] names)
        {
            // 南西2つ・南東2つ・北東2つ・北西2つ
            var at = new[] { (5, 31), (20, 31), (26, 31), (45, 20), (44, 13), (26, 3), (3, 13), (20, 13) };
            var list = new SpotInfo[at.Length];
            for (int i = 0; i < at.Length; i++) list[i] = new SpotInfo { Name = names[i], X = at[i].Item1, Y = at[i].Item2 };
            return list;
        }

