    /// <summary>
    /// ルーネ村のあとに旅する 5つの国の村。
    /// どの村も 48x34 の地図で、4つの区画（南西→南東→北東→北西）に分かれている。
    ///  ・1番目の建物を直す → 南東へのがれき（'1'）が片づく
    ///  ・2番目の建物を直す → 北東へのがれき（'2'）が片づく
    ///  ・3番目の建物を直す → 北西へのがれき（'3'）が片づく
    ///  ・4番目（北西の村のシンボル）を直すと、次の国への手がかりが見つかって 馬車で行けるようになる
    /// </summary>
    public static partial class TownData
