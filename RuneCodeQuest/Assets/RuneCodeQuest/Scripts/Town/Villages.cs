        private const int VW = 48, VH = 34;

        // ----- ほかの国の村で 同じ場所に置くもの -----
        // （プロパティにしておく。Villages の初期化より先に作られている必要があるので）
        private static (int x, int y)[] DefaultBoards => new[] { (12, 21), (31, 21), (31, 7), (17, 8) };
        private static (int x, int y)[] DefaultChests => new[] { (1, 32), (46, 32), (46, 1), (1, 1) };

        private static void Rect(char[,] g, int x0, int y0, int x1, int y1, char c)
        {
            for (int y = y0; y <= y1; y++)
                for (int x = x0; x <= x1; x++)
                    g[x, y] = c;
        }

        /// <summary>区画を分ける かべ（16行目・23列目）を 運河にする（海の町）。門のがれきは そのまま</summary>
        private static void Canals(char[,] g)
        {
            for (int x = 1; x <= VW - 2; x++) if (g[x, 16] == '#') g[x, 16] = '~';
            for (int y = 1; y <= VH - 2; y++) if (g[23, y] == '#') g[23, y] = '~';
        }

        /// <summary>川（x0〜x1・y0〜y1 が水）。bridges の場所に 木の橋をかける</summary>
        private static void River(char[,] g, int x0, int y0, int x1, int y1, params (int x, int y)[] bridges)
        {
            Rect(g, x0, y0, x1, y1, '~');
            foreach (var (x, y) in bridges) g[x, y] = '=';
        }

        private static void Trees(char[,] g, params (int x, int y)[] at)
        {
            foreach (var (x, y) in at) g[x, y] = 'T';
        }

        /// <summary>区画を分けるかべと、がれきの道（16行目・23列目）</summary>
        private static void BaseTerrain(char[,] g)
        {
            Rect(g, 1, 16, VW - 2, 16, '#');
            Rect(g, 23, 1, 23, VH - 2, '#');
            Rect(g, 23, 24, 23, 25, '1');   // 南西 → 南東（1番目の建物が直ると開く）
            Rect(g, 34, 16, 35, 16, '2');   // 南東 → 北東（2番目の建物が直ると開く）
            Rect(g, 23, 7, 23, 8, '3');     // 北東 → 北西（3番目の建物が直ると開く）
        }

        private static VillageInfo NewVillage(int index, string name, string kind, int tileTheme, (byte, byte, byte) wall)
        {
            return new VillageInfo
            {
                Index = index, Name = name, Kind = kind, TileTheme = tileTheme, WallColor = wall,
                W = VW, H = VH, StartX = 12, StartY = 26, SplitX = 23, SplitY = 16,
                AreaGate = new[] { 0, 1, 2, 3 },
                Boards = DefaultBoards, Chests = DefaultChests,
            };
        }

        private static BuildingInfo Bld(int number, string name, BuildingFunction f, int first, int last, (byte, byte, byte) roof, string repaired, params string[] visit)
        {
            // 1番目：南西 ／ 2番目：南東 ／ 3番目：北東 ／ 4番目：北西（村のシンボル。大きい）
            int x = number == 1 ? 4 : number == 4 ? 8 : 37;
            int y = number <= 2 ? 18 : 3;
            return new BuildingInfo
            {
                Number = number, Name = name, Function = f, X = x, Y = y, W = number == 4 ? 7 : 5, H = number == 4 ? 4 : 3,
                FirstStage = first, LastStage = last, Roof = roof, RepairedText = repaired, VisitLines = visit.Length > 0 ? visit : null,
            };
        }

        /// <summary>建物の場所と大きさを 決めなおす（ふつうの置き方と ちがうとき）</summary>
        private static BuildingInfo At(BuildingInfo b, int x, int y, int w, int h)
        {
            b.X = x; b.Y = y; b.W = w; b.H = h;
            return b;
        }

        private static NpcInfo Npc(string name, int x, int y, int after, (byte, byte, byte) cloth, params string[] lines) =>
            new NpcInfo { Name = name, X = x, Y = y, AppearAfter = after, Cloth = cloth, Lines = lines };

