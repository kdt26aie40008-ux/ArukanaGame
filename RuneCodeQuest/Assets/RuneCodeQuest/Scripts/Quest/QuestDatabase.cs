        public static Concept LatestConcept(int level)
        {
            Concept found = null;
            foreach (var kv in Concepts)
                if (kv.Key <= level && (found == null || kv.Key > KeyOf(found))) found = kv.Value;
            return found;
        }

        private static int KeyOf(Concept c)
        {
            foreach (var kv in Concepts) if (kv.Value == c) return kv.Key;
            return 0;
        }

